    print(f"  Physical FKs:    {total_fks}")
    print(f"  Verified xrels:  {len(relationships)}")
    print()
    print(f"  Full JSON:       {full_size:>8,} bytes")
    print(f"  Minified JSON:   {min_size:>8,} bytes  (🔥 {(1 - min_size/full_size)*100:.0f}% smaller)")
    print(f"  Markdown:        {md_size:>8,} bytes")
    print("=" * 60)

